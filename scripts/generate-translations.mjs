// Generates src/fluent/i18n/messages-<lang>.now.ts from src/fluent/i18n/<lang>.json: one
// sys_ui_message per UI string, keyed by the English text that i18n.getMessage() uses. Strings
// the platform already translates (global messages such as "Cancel") are left out of the
// catalog unless the platform translation is wrong for this portal.
// Usage: node scripts/generate-translations.mjs es
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';

const lang = process.argv[2] || 'es';
const dir = new URL('../src/fluent/i18n/', import.meta.url);
const catalog = JSON.parse(readFileSync(new URL(`${lang}.json`, dir), 'utf8'));

const records = Object.entries(catalog).map(([key, message]) => {
  const id = createHash('sha1').update(key).digest('hex').slice(0, 12);
  return `Record({
    $id: Now.ID['luxesc-${lang}-${id}'],
    table: 'sys_ui_message',
    data: { key: ${JSON.stringify(key)}, message: ${JSON.stringify(message)}, language: '${lang}' },
})`;
});

writeFileSync(
  new URL(`messages-${lang}.now.ts`, dir),
  `// Generated by scripts/generate-translations.mjs from ${lang}.json; edit the JSON, not this file.
import '@servicenow/sdk/global'
import { Record } from '@servicenow/sdk/core'

${records.join('\n\n')}
`
);
console.log(`${records.length} ${lang} messages written`);
